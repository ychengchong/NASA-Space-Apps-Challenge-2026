"""Generate TypeScript contracts from Pydantic JSON Schema, without another dependency."""

import argparse
import json
from pathlib import Path
from typing import Any

from pydantic import TypeAdapter

from app import models

DESTINATION = Path(__file__).resolve().parents[2] / "frontend/src/generatedModels.ts"


def ts_type(schema: dict[str, Any]) -> str:
    """Translate the schema constructs used by our shared models; fail on unknown constructs."""
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "anyOf" in schema:
        return "(" + " | ".join(ts_type(item) for item in schema["anyOf"]) + ")"
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind in ("number", "integer"):
        return "number"
    if kind in ("string", "boolean", "null"):
        return kind
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts_type(item) for item in schema["prefixItems"]) + "]"
        return f"({ts_type(schema['items'])})[]"
    raise ValueError(f"Unsupported shared schema: {schema}")


def generate() -> str:
    """One definition per shared type; preserve aliases/default optionality in the contracts."""
    definitions = {}
    for name, value in vars(models).items():
        if (
            isinstance(value, type)
            and issubclass(value, models.Model)
            and value is not models.Model
        ):
            schema = value.model_json_schema(by_alias=True)
            definitions.update(schema.pop("$defs", {}))
            definitions[name] = schema
    lines = ["// Generated by backend/scripts/generate_types.py. Do not edit by hand.", ""]
    for name in ("Season", "Resolution", "VerdictKind", "Direction", "Contrast", "Caution"):
        lines.append(
            f"export type {name} = {ts_type(TypeAdapter(getattr(models, name)).json_schema())};"
        )
    lines.append('export type PlaceKind = PlaceCandidate["kind"];')
    for name, schema in sorted(definitions.items()):
        lines.extend(["", f"export interface {name} {{"])
        required = schema.get("required", [])
        for key, field in schema["properties"].items():
            optional = "" if key in required else "?"
            lines.append(f"  {json.dumps(key)}{optional}: {ts_type(field)};")
        lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text(encoding="utf-8") != output:
            raise SystemExit("Shared types are stale: run python -m scripts.generate_types")
    else:
        DESTINATION.write_text(output, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
